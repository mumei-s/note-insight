const publicDir = new URL('../public/', import.meta.url);
const output = new URL('note-card-batch-bridge-v610.user.js', publicDir);
const header = "// ==UserScript==\n// @name         無名S note 極薄＋通知 URL/# 18.8.16\n// @namespace    https://github.com/mumei-s/note-insight/batch-bridge-610\n// @version      18.9.21\n// @description  緊急停止版。note上では極薄・通知カード処理、通信監視、自動再開を一切起動しません。\n// @match        https://editor.note.com/*\n// @updateURL    https://raw.githubusercontent.com/mumei-s/note-insight/main/public/note-card-batch-bridge-v610.user.js\n// @downloadURL  https://raw.githubusercontent.com/mumei-s/note-insight/main/public/note-card-batch-bridge-v610.user.js\n// @run-at       document-start\n// @grant        GM_xmlhttpRequest\n// @grant        unsafeWindow\n// @connect      note.com\n// @connect      assets.st-note.com\n// @connect      mumei-s.github.io\n// @connect      raw.githubusercontent.com\n// ==/UserScript==\n\n// Generated by scripts/build-card-userscript.mjs. Update modules, then rebuild.\n// One installable file prevents mixed cached @require versions.\n";
