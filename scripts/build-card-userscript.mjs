export function wrapModules(body) {
  return prelude + body + footer;
}
export function build() {
  const body = modules.map(name => '// MODULE: ' + name + '\n' + readFileSync(new URL(name, publicDir), 'utf8')).join('');
  return header + wrapModules(body);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== build()) throw new Error('Card userscript differs from its source modules. Run node scripts/build-card-userscript.mjs');
    console.log('Card userscript source/bundle: identical');
  } else {
    writeFileSync(output, build());
    console.log('Built v18.9.21 emergency-stop card userscript');
  }
}
