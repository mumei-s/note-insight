import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const modules = [
  'note-card-safety-v188.js',
  'note-thin-image-cache-v1882.js',
  'note-card-creator-v1883.js',
  'note-likers-thin-notify-v160.js',
  'note-source-picker-v163.js',
  'note-start-clean-v177.js',
  'note-link-guard-v178.js',
  'note-tool-floating-ui-v164.js',
  'note-prince-special-v184.js',
  'note-generic-stability-v187.js',
  'note-generic-controls-v189.js',
  'note-yoizora-additions-v1886.js',
  'note-prepared-batch-v1883.js',
];
const publicDir = new URL('../public/', import.meta.url);
const output = new URL('note-card-batch-bridge-v610.user.js', publicDir);
const header = `// ==UserScript==
// @name         無名S note 極薄＋通知 URL/# 18.8.11
// @namespace    https://github.com/mumei-s/note-insight/batch-bridge-610
// @version      18.8.11
// @description  投稿者照合・全件名前＋さんのキャプション。作成済み画像を連続投入、#先頭、最後は実績の算数。極薄の初期化と通知カード一括削除。
// @match        https://editor.note.com/*
// @updateURL    https://raw.githubusercontent.com/mumei-s/note-insight/main/public/note-card-batch-bridge-v610.user.js
// @downloadURL  https://raw.githubusercontent.com/mumei-s/note-insight/main/public/note-card-batch-bridge-v610.user.js
// @run-at       document-start
// @grant        GM_xmlhttpRequest
// @grant        unsafeWindow
// @connect      note.com
// @connect      assets.st-note.com
// @connect      mumei-s.github.io
// ==/UserScript==

// Generated by scripts/build-card-userscript.mjs. Update modules, then rebuild.
// One installable file prevents mixed cached @require versions.
`;
export function build() {
  return header + modules.map(name => '\n// MODULE: ' + name + '\n' + readFileSync(new URL(name, publicDir), 'utf8').trimEnd() + '\n').join('');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(output, 'utf8') !== build()) throw new Error('Card userscript differs from its source modules. Run node scripts/build-card-userscript.mjs');
    console.log('Card userscript source/bundle: identical');
  } else {
    writeFileSync(output, build());
    console.log('Built v18.8.11 standalone card userscript');
  }
}
